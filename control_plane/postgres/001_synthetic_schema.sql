-- CHEMFORGE Control PostgreSQL synthetic-only schema v1.
-- Run only against a disposable, dedicated, private-loopback PostgreSQL CI database.
-- No real school data, Nexus data, OIDC secrets, or public endpoints.
CREATE TABLE tenants (
    id TEXT PRIMARY KEY,
    created_at TEXT NOT NULL
);
CREATE TABLE actors (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    label TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'teacher')),
    token_hash TEXT NOT NULL UNIQUE,
    revoked_at TEXT,
    created_at TEXT NOT NULL,
    UNIQUE (tenant_id, id)
);
CREATE INDEX idx_actors_tenant ON actors(tenant_id, role);
CREATE TABLE oidc_actor_links (
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    actor_id TEXT NOT NULL UNIQUE,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    linked_at TEXT NOT NULL,
    PRIMARY KEY (issuer, subject),
    FOREIGN KEY (tenant_id, actor_id) REFERENCES actors(tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_oidc_actor_links ON oidc_actor_links(tenant_id, actor_id);
CREATE TABLE oidc_auth_flows (
    state_hash TEXT PRIMARY KEY,
    binding_hash TEXT NOT NULL,
    code_verifier TEXT NOT NULL,
    nonce TEXT NOT NULL,
    expires_at TEXT NOT NULL
);
CREATE INDEX idx_oidc_auth_expires ON oidc_auth_flows(expires_at);
CREATE TABLE oidc_browser_sessions (
    session_hash TEXT PRIMARY KEY,
    actor_id TEXT NOT NULL,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    csrf_token TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    created_at TEXT NOT NULL,
    FOREIGN KEY (tenant_id, actor_id) REFERENCES actors(tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_oidc_session_expires ON oidc_browser_sessions(expires_at);
CREATE TABLE teacher_cohorts (
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    actor_id TEXT NOT NULL,
    cohort TEXT NOT NULL,
    granted_at TEXT NOT NULL,
    PRIMARY KEY (tenant_id, actor_id, cohort),
    FOREIGN KEY (tenant_id, actor_id) REFERENCES actors(tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_teacher_cohorts ON teacher_cohorts(tenant_id, actor_id, cohort);
CREATE TABLE students (
    id TEXT NOT NULL,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    pseudonym TEXT NOT NULL,
    cohort TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (tenant_id, id)
);
CREATE INDEX idx_student_cohort ON students(tenant_id, cohort);
CREATE TABLE assignments (
    id TEXT NOT NULL,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    title TEXT NOT NULL,
    cohort TEXT NOT NULL,
    objectives_json TEXT NOT NULL,
    due_at TEXT,
    actor_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (tenant_id, id),
    FOREIGN KEY (tenant_id, actor_id) REFERENCES actors(tenant_id, id)
);
CREATE TABLE evidence (
    tenant_id TEXT NOT NULL,
    event_id TEXT NOT NULL,
    student_id TEXT NOT NULL,
    question_id TEXT NOT NULL,
    payload_sha256 TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    verification_status TEXT NOT NULL CHECK (verification_status = 'unverified_import'),
    received_at TEXT NOT NULL,
    PRIMARY KEY (tenant_id, event_id),
    FOREIGN KEY (tenant_id, student_id) REFERENCES students(tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_evidence_student ON evidence(tenant_id, student_id);
CREATE TABLE devices (
    id TEXT PRIMARY KEY,
    tenant_id TEXT NOT NULL,
    student_id TEXT NOT NULL,
    label TEXT NOT NULL,
    token_hash TEXT NOT NULL UNIQUE,
    issued_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    revoked_at TEXT,
    FOREIGN KEY (tenant_id, student_id) REFERENCES students(tenant_id, id) ON DELETE CASCADE
);
CREATE INDEX idx_devices_student ON devices(tenant_id, student_id);
CREATE TABLE content_releases (
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    pack_version INTEGER NOT NULL CHECK (pack_version >= 1),
    content_version TEXT NOT NULL,
    pack_sha256 TEXT NOT NULL,
    content_fingerprint TEXT NOT NULL,
    actor_id TEXT NOT NULL,
    created_at TEXT NOT NULL,
    PRIMARY KEY (tenant_id, pack_version),
    FOREIGN KEY (tenant_id, actor_id) REFERENCES actors(tenant_id, id)
);
CREATE TABLE audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL REFERENCES tenants(id),
    actor_id TEXT NOT NULL,
    action TEXT NOT NULL,
    subject_id TEXT NOT NULL,
    occurred_at TEXT NOT NULL
);
CREATE INDEX idx_audit_tenant ON audit(tenant_id, id);
